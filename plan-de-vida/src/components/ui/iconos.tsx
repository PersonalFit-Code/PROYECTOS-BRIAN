export function iconoDe(nombre: string | null | undefined, porDefecto = "circle"): LucideIcon {
  return (nombre && ICONOS[nombre]?.icono) || ICONOS[porDefecto]?.icono || Circle;
}

/** Icono guardado por nombre (hábito, categoría, área…). Un valor desconocido pinta un círculo. */
export function Icono({ nombre, className, porDefecto }: { nombre: string | null | undefined; className?: string; porDefecto?: string }) {
  return createElement(iconoDe(nombre, porDefecto), { className: cx("size-4 shrink-0", className), "aria-hidden": true });
}

/** Icono dentro de un cuadradito de cristal con el color del área o la categoría. */
export function IconoCaja({ nombre, color = "gray", tamano = "md", className, porDefecto }: { nombre: string | null | undefined; color?: string; tamano?: "sm" | "md" | "lg"; className?: string; porDefecto?: string }) {
  const caja = { sm: "size-7 rounded-lg", md: "size-9 rounded-xl", lg: "size-12 rounded-2xl" }[tamano];
  const icono = { sm: "size-3.5", md: "size-4.5", lg: "size-6" }[tamano];
  return (
    <span className={cx("grid shrink-0 place-items-center", caja, className)} style={{ background: `var(--tag-${color}-bg)`, color: `var(--tag-${color}-fg)` }}>
      <Icono nombre={nombre} className={icono} porDefecto={porDefecto} />
    </span>
  );
}
